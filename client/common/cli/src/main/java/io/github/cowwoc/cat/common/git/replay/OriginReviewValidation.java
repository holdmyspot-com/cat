package io.github.cowwoc.cat.common.git.replay;

import java.io.IOException;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;
import java.util.stream.Collectors;

/**
 * Validates the policy that places reviewed changes with their exact-path predecessors.
 */
public final class OriginReviewValidation
{
	private final PathStateReader pathStates;

	/**
	 * Creates an origin-review policy validator.
	 *
	 * @param history immutable Git tree-state access
	 */
	OriginReviewValidation(History history)
	{
		this(history::pathState);
	}

	/**
	 * Creates an origin-review policy validator from captured path-state access.
	 *
	 * @param pathStates reads the immutable state of one path in a captured tree
	 */
	public OriginReviewValidation(PathStateReader pathStates)
	{
		this.pathStates = pathStates;
	}

	/**
	 * Validates required origin reviews without inferring semantic equivalence or destination placement.
	 *
	 * @param manifest the replay manifest
	 * @param candidates immutable Git-derived origin candidates
	 * @param reviews the reviewer-authored origin reviews
	 * @param sourceReviews recorded source reviews
	 * @param requireRecordedReviews whether missing required reviews fail validation
	 * @param sourceReviewValidation source-review policy used to locate predecessor outputs
	 * @throws IOException if a required review is missing or contradicts deterministic Git facts
	 */
	void validate(BatchManifest manifest, List<OriginCandidate> candidates, List<OriginReview> reviews,
		List<SourceReview> sourceReviews, boolean requireRecordedReviews, SourceReviewValidation sourceReviewValidation)
		throws IOException
	{
		if (candidates.isEmpty())
		{
			if (!reviews.isEmpty())
			{
				throw new IOException("Topic-replay origin reviews must not name a path without an exact-path predecessor");
			}
			return;
		}
		if (requireRecordedReviews && reviews.isEmpty())
		{
			throw new IOException("Topic-replay preflight requires origin reviews. Run origin-candidates, record " +
				"the reviewer-selected destinations, and then run record-origin-reviews.");
		}
		Map<String, OriginCandidate> candidatesByItem = candidates.stream().collect(Collectors.toMap(
			OriginCandidate::inventoryId, Function.identity()));
		Map<String, SourceReview> sourceReviewsBySource = sourceReviews.stream().collect(Collectors.toMap(
			SourceReview::source, Function.identity()));
		Map<String, Output> outputs = manifest.outputs().stream().collect(Collectors.toMap(Output::id,
			Function.identity()));
		Set<String> reviewedItems = new HashSet<>();
		Set<String> evidence = new HashSet<>();
		List<String> placementProblems = new ArrayList<>();
		for (OriginReview review : reviews)
		{
			validateReviewFacts(review, reviewedItems, evidence);
			OriginCandidate candidate = candidatesByItem.get(review.inventoryId());
			if (candidate == null || !candidate.predecessors().equals(review.predecessors()))
			{
				throw new IOException("Origin review " + review.inventoryId() +
					" must retain the exact predecessor candidates generated by Git");
			}
			if (review.classification().equals("different_unit"))
			{
				validateDifferentUnitSelection(review);
				continue;
			}
			validateSameUnitSelection(review, outputs.keySet());
			Set<String> rejected = validateRejectedDestinations(review, outputs.keySet());
			int selectedIndex = outputIndex(manifest.outputs(), review.destination());
			InventoryItem item = manifest.inventory().stream().filter(candidateItem -> candidateItem.id().equals(
				review.inventoryId())).findFirst().orElseThrow();
			for (String predecessor : candidate.predecessors())
			{
				String output = sourceReviewValidation.sourceOutput(manifest, predecessor);
				if (output == null)
					continue;
				if (outputIndex(manifest.outputs(), output) < selectedIndex && !rejected.contains(output))
				{
					placementProblems.add(item.path() + " is assigned to " + outputDescription(outputs.get(
						review.destination())) + " without explaining why the earlier possible output " +
						outputDescription(outputs.get(output)) + " lacks a required prerequisite");
				}
			}
			if (requireRecordedReviews)
				validateRecordedPlacement(manifest, sourceReviewsBySource, review, item, outputs,
					sourceReviewValidation, placementProblems);
		}
		if (requireRecordedReviews && !reviewedItems.equals(candidatesByItem.keySet()))
		{
			throw new IOException("Origin reviews must account for every generated candidate exactly once");
		}
		throwPlacementProblems(placementProblems, requireRecordedReviews);
	}

	/**
	 * Validates that a different-unit review does not place the change with a predecessor.
	 *
	 * @param review the reviewer decision
	 * @throws IOException if the decision selects a destination or gives the wrong relationship
	 */
	private void validateDifferentUnitSelection(OriginReview review) throws IOException
	{
		if (!review.predecessorRelationship().equals("introduces_independent_responsibility"))
		{
			throw new IOException("A different-unit origin review must explain that it introduces an independent " +
				"responsibility");
		}
		if (review.destination() != null || review.rejectedDestinations() != null &&
			!review.rejectedDestinations().isEmpty())
		{
			throw new IOException("A different-unit origin review must not select or reject an output");
		}
	}

	/**
	 * Validates and indexes destinations the reviewer rejected for a same-unit change.
	 *
	 * @param review the reviewer decision
	 * @param outputIds declared output identifiers
	 * @return the uniquely rejected output identifiers
	 * @throws IOException if a rejection is incomplete, unknown, or duplicated
	 */
	private Set<String> validateRejectedDestinations(OriginReview review, Set<String> outputIds) throws IOException
	{
		Set<String> rejected = new HashSet<>();
		if (review.rejectedDestinations() == null)
			return rejected;
		for (RejectedDestination rejection : review.rejectedDestinations())
		{
			if (rejection == null || rejection.output() == null || !outputIds.contains(rejection.output()) ||
				rejection.missingPrerequisite() == null || rejection.missingPrerequisite().isBlank() ||
				!rejected.add(rejection.output()))
			{
				throw new IOException("Every rejected origin destination requires one output and missing prerequisite");
			}
		}
		return rejected;
	}

	/**
	 * Checks that a recorded same-unit placement can contain the reviewed path change.
	 *
	 * @param manifest the replay manifest
	 * @param sourceReviewsBySource recorded source reviews indexed by source commit
	 * @param review the reviewer decision
	 * @param item the reviewed inventory item
	 * @param outputs declared outputs indexed by identifier
	 * @param sourceReviewValidation source-review policy used to identify discarded outputs
	 * @param placementProblems accumulated placement contradictions
	 * @throws IOException if Git tree state needed to verify the placement cannot be read
	 */
	private void validateRecordedPlacement(BatchManifest manifest, Map<String, SourceReview> sourceReviewsBySource,
		OriginReview review, InventoryItem item, Map<String, Output> outputs,
		SourceReviewValidation sourceReviewValidation, List<String> placementProblems) throws IOException
	{
		SourceReview sourceReview = sourceReviewsBySource.get(item.source());
		if (sourceReview != null && sourceReview.disposition().equals("absorbed") &&
			sourceReviewValidation.isDiscardedSourceOutput(manifest, item.source()))
		{
			return;
		}
		boolean destinationRetained = manifest.outputWitnesses().stream().anyMatch(witness -> witness.outputId().equals(
			review.destination()));
		if (!destinationRetained)
		{
			placementProblems.add(item.path() + " from source " + item.source() + " is assigned to " +
				outputDescription(outputs.get(review.destination())) + ", but the output is discarded and cannot " +
				"contain the reviewed change");
			return;
		}
		if (!sourceChangesPath(manifest, item, review.destination()) && !isSourcePathStateAtDestination(manifest, item,
			review.destination()))
		{
			placementProblems.add(item.path() + " from source " + item.source() + " is assigned to " +
				outputDescription(outputs.get(review.destination())) + ", but that output has no planned batch from " +
				"the source that changes the path or produces its resulting path state");
		}
	}

	/**
	 * Indicates whether a batch from the reviewed source changes its path in the selected output.
	 *
	 * @param manifest the replay manifest
	 * @param item the reviewed inventory item
	 * @param destination the selected output
	 * @return {@code true} if a matching batch changes the path
	 * @throws IOException if Git tree state needed to compare the batch cannot be read
	 */
	private boolean sourceChangesPath(BatchManifest manifest, InventoryItem item, String destination) throws IOException
	{
		for (Batch batch : manifest.batches())
		{
			if (!batch.source().equals(item.source()) || !batch.destination().equals(destination))
				continue;
			PathState stateBeforeBatch = pathStates.read(batch.destinationWitness().beforeTree(), item.path());
			PathState stateAfterBatch = pathStates.read(batch.destinationWitness().afterTree(), item.path());
			if (!stateBeforeBatch.equals(stateAfterBatch))
				return true;
		}
		return false;
	}

	/**
	 * Reports accumulated origin-placement contradictions using the active review stage's recovery guidance.
	 *
	 * @param placementProblems contradictions found while validating review decisions
	 * @param requireRecordedReviews whether validation is sealing a complete output plan
	 * @throws IOException if one or more placement contradictions were found
	 */
	private void throwPlacementProblems(List<String> placementProblems, boolean requireRecordedReviews) throws IOException
	{
		if (placementProblems.isEmpty())
			return;
		if (requireRecordedReviews)
		{
			throw new IOException("Topic-replay output plan conflicts with recorded origin decisions:\n- " +
				String.join("\n- ", placementProblems) + "\nCorrect the plan by assigning the reviewed source " +
				"change to that output, or re-review the destination when the earlier decision no longer applies. Then " +
				"seal the complete plan again before recording any output.");
		}
		throw new IOException("Recorded origin reviews conflict with recorded origin decisions:\n- " +
			String.join("\n- ", placementProblems) + "\nSelect the earlier output or record why it lacks the " +
			"required prerequisite before saving the origin review.");
	}

	/**
	 * Finds an output's chronological position in the rewritten history.
	 *
	 * @param outputs declared outputs in chronological order
	 * @param outputId the output identifier
	 * @return the zero-based output position
	 * @throws AssertionError if {@code outputId} is not declared
	 */
	private int outputIndex(List<Output> outputs, String outputId)
	{
		for (int index = 0; index < outputs.size(); ++index)
		{
			if (outputs.get(index).id().equals(outputId))
				return index;
		}
		throw new AssertionError("Unknown topic-replay output: " + outputId);
	}

	/**
	 * Indicates whether a reviewer relationship describes a change to the same responsibility.
	 *
	 * @param relationship the reviewer-supplied predecessor relationship
	 * @return {@code true} if the relationship describes a same-unit change
	 */
	boolean isSameUnitRelationship(String relationship)
	{
		return switch (relationship)
		{
			case "corrects_predecessor", "reverts_predecessor", "tests_predecessor", "documents_predecessor",
				"configures_predecessor", "removes_invalid_predecessor" -> true;
			default -> false;
		};
	}

	/**
	 * Describes one logical output using both its stable identifier and its reader-facing responsibility.
	 *
	 * @param output the output to describe
	 * @return a readable output description
	 */
	String outputDescription(Output output)
	{
		return output.id() + " (" + output.subject() + ")";
	}

	/**
	 * Validates the shape of one reviewer-selected same-unit destination.
	 *
	 * @param review the reviewer decision
	 * @param outputIds declared output identifiers
	 * @throws IOException if the decision does not name a supported same-unit relationship and output
	 */
	void validateSameUnitSelection(OriginReview review, Set<String> outputIds) throws IOException
	{
		if (!"same_unit".equals(review.classification()) || !isSameUnitRelationship(review.predecessorRelationship()) ||
			review.destination() == null || !outputIds.contains(review.destination()))
		{
			throw new IOException("A same-unit origin review must name a correction, reversion, test, " +
				"documentation, " +
				"configuration, or invalid-artifact-removal relationship and a destination");
		}
	}

	/**
	 * Validates the reviewer-provided facts shared by every origin decision.
	 *
	 * @param review the reviewer decision
	 * @param reviewedItems identifiers already reviewed
	 * @param evidence values already used as placement evidence
	 * @throws java.io.IOException if the decision is incomplete or duplicates evidence
	 */
	void validateReviewFacts(OriginReview review, Set<String> reviewedItems, Set<String> evidence) throws IOException
	{
		if (review == null || review.inventoryId() == null || !reviewedItems.add(review.inventoryId()) ||
			review.classification() == null || review.affectedUnit() == null || review.affectedUnit().isBlank() ||
			review.owningResponsibility() == null || review.owningResponsibility().isBlank() ||
			review.predecessorRelationship() == null || review.predecessorRelationship().isBlank() ||
			review.evidence() == null || review.evidence().isBlank())
		{
			throw new IOException("Every origin review requires its candidate, affected unit, " +
				"owning responsibility, " +
				"predecessor relationship, classification, and evidence");
		}
		if (!evidence.add(review.evidence()))
		{
			throw new IOException("Origin-review evidence must be specific to one affected unit; " +
				"repeated evidence is " +
				"not a reviewed placement decision");
		}
	}

	/**
	 * Indicates whether a source's changed path has the same final state at its selected destination.
	 *
	 * @param manifest the replay manifest
	 * @param item the reviewed source-path change
	 * @param destination the selected output
	 * @return {@code true} if the changed path has the same state at the destination
	 * @throws java.io.IOException if a required Git tree cannot be read
	 */
	boolean isSourcePathStateAtDestination(BatchManifest manifest, InventoryItem item, String destination)
		throws IOException
	{
		SourceSnapshot source = manifest.sources().stream().filter(candidate -> candidate.hash().equals(item.source())).
			findFirst().orElseThrow();
		OutputWitness output = manifest.outputWitnesses().stream().filter(witness -> witness.outputId().equals(
			destination)).
			findFirst().orElseThrow(() -> new IOException("Topic-replay manifest does not contain retained output: " +
				destination));
		return pathStates.read(source.tree(), item.path()).equals(pathStates.read(output.afterTree(), item.path()));
	}

	/**
	 * Reads captured path facts used by {@link OriginReviewValidation} to check output placement.
	 */
	@FunctionalInterface
	public interface PathStateReader
	{
		/**
		 * Reads a repository-relative path's state in one immutable tree.
		 *
		 * @param tree the captured tree identity
		 * @param path the repository-relative path
		 * @return the path's captured state, including absence
		 * @throws IOException if the tree's path facts cannot be read
		 */
		PathState read(String tree, String path) throws IOException;
	}
}
