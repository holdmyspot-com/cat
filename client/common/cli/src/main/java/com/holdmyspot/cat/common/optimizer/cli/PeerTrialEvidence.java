package com.holdmyspot.cat.common.optimizer.cli;

import com.holdmyspot.cat.common.FileReplacer;
import com.holdmyspot.cat.common.optimizer.evidence.ActivityFile;
import com.holdmyspot.cat.common.optimizer.evidence.SessionEvidence;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.function.UnaryOperator;
import tools.jackson.databind.json.JsonMapper;

/**
 * Keeps the peer harness's parsed trial activity beside its retained native transcript.
 */
final class PeerTrialEvidence
{
	private static final String FILE = "evaluator-evidence.json";

	/**
	 * Keeps evidence generated by the evaluator's native parser before the owner can see the completed turn.
	 *
	 * @param json       the process mapper
	 * @param replacer   atomically replaces the previous turn's evidence
	 * @param transcript the retained native events
	 * @param evidence   the native parser's result
	 * @throws IOException if the activity cannot be retained
	 */
	static void write(JsonMapper json, FileReplacer replacer, Path transcript, SessionEvidence evidence)
		throws IOException
	{
		Path temporary = Files.createTempFile(transcript.getParent(), "evaluator-evidence-", ".tmp");
		try
		{
			ActivityFile.write(json, temporary, evidence);
			replacer.replace(temporary, transcript.resolveSibling(FILE));
		}
		finally
		{
			Files.deleteIfExists(temporary);
		}
	}

	/**
	 * Reads activity retained by the peer, including after the campaign resumes in another owner process.
	 *
	 * @param json       the process mapper
	 * @param transcript the retained native events
	 * @return the parsed native activity
	 * @throws IOException if the evidence is absent or malformed
	 */
	static SessionEvidence read(JsonMapper json, Path transcript) throws IOException
	{
		Path sidecar = transcript.resolveSibling(FILE);
		if (!Files.isRegularFile(sidecar, LinkOption.NOFOLLOW_LINKS))
			throw new IOException("The evaluator did not retain parsed activity for " + transcript);
		return ActivityFile.read(json, sidecar, UnaryOperator.identity());
	}

	/**
	 * Prevents construction.
	 */
	private PeerTrialEvidence()
	{
	}
}
