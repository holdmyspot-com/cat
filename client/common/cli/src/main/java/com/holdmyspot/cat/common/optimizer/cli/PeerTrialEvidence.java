package com.holdmyspot.cat.common.optimizer.cli;

import com.holdmyspot.cat.common.FileReplacer;
import com.holdmyspot.cat.common.optimizer.evidence.CommandSummary;
import com.holdmyspot.cat.common.optimizer.evidence.SessionEvidence;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import tools.jackson.core.JacksonException;
import tools.jackson.core.type.TypeReference;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.ObjectNode;

/**
 * Keeps the peer harness's parsed trial activity beside its retained native transcript.
 */
final class PeerTrialEvidence
{
	private static final String FILE = "evaluator-evidence.json";
	private static final int VERSION = 1;
	private static final TypeReference<List<String>> STRINGS = new TypeReference<>()
	{
	};

	/**
	 * Keeps evidence generated by the evaluator's native parser before the owner can see the completed turn.
	 *
	 * @param json       the process mapper
	 * @param replacer   atomically replaces the previous turn's evidence
	 * @param transcript the retained native events
	 * @param evidence   the native parser's result
	 * @throws IOException if the activity cannot be retained
	 */
	static void write(JsonMapper json, FileReplacer replacer, Path transcript, SessionEvidence evidence)
		throws IOException
	{
		ObjectNode document = json.createObjectNode().put("format_version", VERSION);
		ArrayNode entries = document.putArray("entries");
		for (SessionEvidence.Entry entry : evidence.entries())
			writeEntry(json, entries.addObject(), entry);
		document.set("received", json.valueToTree(evidence.received()));
		Duration slowest = evidence.commands().slowest();
		Integer empty = evidence.commands().emptyRunningResults();
		if (slowest != null)
			document.put("slowest_command", slowest.toString());
		if (empty != null)
			document.put("empty_running_results", empty);
		Path temporary = Files.createTempFile(transcript.getParent(), "evaluator-evidence-", ".tmp");
		try
		{
			json.writeValue(temporary.toFile(), document);
			replacer.replace(temporary, transcript.resolveSibling(FILE));
		}
		finally
		{
			Files.deleteIfExists(temporary);
		}
	}

	/**
	 * Writes an activity entry without opening the native evidence package for reflective access.
	 *
	 * @param json   the process mapper
	 * @param record the activity record
	 * @param entry  the parsed native entry
	 */
	private static void writeEntry(JsonMapper json, ObjectNode record, SessionEvidence.Entry entry)
	{
		ObjectNode node = record.putObject("entry").put("turn", entry.turn()).put("agent", entry.agent());
		switch (entry)
		{
			case SessionEvidence.Tool tool ->
			{
				record.put("type", "tool");
				node.put("tool", tool.tool()).put("input", tool.input()).put("command", tool.command()).
					put("exit_status", tool.exitStatus()).put("output", tool.output()).
					set("running", json.valueToTree(tool.running()));
			}
			case SessionEvidence.CommandEnd command ->
			{
				record.put("type", "command_end");
				node.put("input", command.input()).put("exit_status", command.exitStatus()).put("output", command.output());
			}
			case SessionEvidence.Hook hook ->
			{
				record.put("type", "hook");
				node.put("hook", hook.hook()).put("status", hook.status());
			}
			case SessionEvidence.Assistant assistant ->
			{
				record.put("type", "assistant");
				node.put("position", assistant.position()).put("text", assistant.text());
				ArrayNode questions = node.putArray("questions");
				for (SessionEvidence.Question question : assistant.questions())
					questions.addObject().put("title", question.title()).set("options", json.valueToTree(question.options()));
			}
			case SessionEvidence.ChildEvent event ->
			{
				record.put("type", "child_event");
				node.put("child", event.child()).put("name", event.name()).put("kind", event.kind().name()).
					put("text", event.text());
			}
		}
	}

	/**
	 * Reads activity retained by the peer, including after the campaign resumes in another owner process.
	 *
	 * @param json       the process mapper
	 * @param transcript the retained native events
	 * @return the parsed native activity
	 * @throws IOException if the evidence is absent or malformed
	 */
	static SessionEvidence read(JsonMapper json, Path transcript) throws IOException
	{
		Path sidecar = transcript.resolveSibling(FILE);
		if (!Files.isRegularFile(sidecar, LinkOption.NOFOLLOW_LINKS))
			throw new IOException("The evaluator did not retain parsed activity for " + transcript);
		try
		{
			JsonNode document = json.readTree(sidecar.toFile());
			if (PeerTrialProtocol.number(document, "format_version") != VERSION)
				throw new IOException("Unsupported retained evaluator activity format");
			JsonNode records = document.path("entries");
			if (!records.isArray() || !document.path("received").isArray())
				throw new IOException("Malformed retained evaluator activity");
			List<SessionEvidence.Entry> entries = new ArrayList<>();
			for (JsonNode record : records)
				entries.add(readEntry(json, record));
			Duration slowest = null;
			Integer empty = null;
			if (document.has("slowest_command"))
				slowest = Duration.parse(PeerTrialProtocol.text(document, "slowest_command"));
			if (document.has("empty_running_results"))
				empty = PeerTrialProtocol.number(document, "empty_running_results");
			return new SessionEvidence(entries, json.convertValue(document.path("received"), STRINGS),
				new CommandSummary(slowest, empty));
		}
		catch (JacksonException | IllegalArgumentException e)
		{
			throw new IOException("Malformed retained evaluator activity", e);
		}
	}

	/**
	 * Reconstructs a field-checked activity entry.
	 *
	 * @param json   the process mapper
	 * @param record the stored activity record
	 * @return the semantically typed activity
	 * @throws IOException if the entry is malformed
	 */
	private static SessionEvidence.Entry readEntry(JsonMapper json, JsonNode record) throws IOException
	{
		JsonNode node = record.path("entry");
		int turn = PeerTrialProtocol.number(node, "turn");
		String agent = PeerTrialProtocol.text(node, "agent");
		return switch (PeerTrialProtocol.type(record))
		{
			case "tool" -> new SessionEvidence.Tool(turn, agent, PeerTrialProtocol.text(node, "tool"),
				PeerTrialProtocol.text(node, "input"), node.path("command").booleanValue(), exitStatus(node),
				PeerTrialProtocol.text(node, "output"), json.convertValue(node.path("running"), STRINGS));
			case "command_end" -> new SessionEvidence.CommandEnd(turn, agent, PeerTrialProtocol.text(node, "input"),
				exitStatus(node), PeerTrialProtocol.text(node, "output"));
			case "hook" -> new SessionEvidence.Hook(turn, agent, PeerTrialProtocol.text(node, "hook"),
				PeerTrialProtocol.text(node, "status"));
			case "assistant" -> new SessionEvidence.Assistant(turn, agent, PeerTrialProtocol.number(node, "position"),
				PeerTrialProtocol.text(node, "text"), questions(json, node.path("questions")));
			case "child_event" -> new SessionEvidence.ChildEvent(turn, agent, PeerTrialProtocol.text(node, "child"),
				PeerTrialProtocol.text(node, "name"),
				SessionEvidence.ChildEvent.Kind.valueOf(PeerTrialProtocol.text(node, "kind")),
				PeerTrialProtocol.text(node, "text"));
			default -> throw new IOException("Unknown retained evaluator activity type");
		};
	}

	/**
	 * Reads the nullable process exit status.
	 *
	 * @param node the tool or command entry
	 * @return its status, or null when the native record omitted it
	 * @throws IOException if the recorded status is malformed
	 */
	private static Integer exitStatus(JsonNode node) throws IOException
	{
		if (node.path("exit_status").isNull())
			return null;
		return PeerTrialProtocol.number(node, "exit_status");
	}

	/**
	 * Reads any user-input questions and their options in order.
	 *
	 * @param json the process mapper
	 * @param node the questions array
	 * @return the questions the assistant asked
	 * @throws IOException if a question is malformed
	 */
	private static List<SessionEvidence.Question> questions(JsonMapper json, JsonNode node) throws IOException
	{
		if (!node.isArray())
			throw new IOException("Expected retained evaluator questions");
		List<SessionEvidence.Question> questions = new ArrayList<>();
		for (JsonNode question : node)
		{
			questions.add(new SessionEvidence.Question(PeerTrialProtocol.text(question, "title"),
				json.convertValue(question.path("options"), STRINGS)));
		}
		return questions;
	}

	/**
	 * Prevents construction.
	 */
	private PeerTrialEvidence()
	{
	}
}
